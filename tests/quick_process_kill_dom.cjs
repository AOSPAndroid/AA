const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const {fixture, root} = require('./ui_fixture.cjs');
const settle = () => new Promise(resolve => setTimeout(resolve, 0));
(async () => {
  const kills = [];
  const f = await fixture({fetch: async (url, options = {}) => {
    if (url === '/api/session') return {ok: true, json: async () => ({token: 'test'})};
    if (url === '/api/kill') return new Promise(resolve => kills.push({payload: JSON.parse(options.body), resolve: data => resolve({ok: true, json: async () => data})}));
    throw Error('Unexpected request ' + url);
  }});
  const {w, run} = f, get = id => w.document.getElementById(id);
  run(fs.readFileSync(path.join(root, 'frontend/assets/app.js'), 'utf8'));
  run('var notices=[]; function toast(message){notices.push(message)}; async function copy(){}');
  run(fs.readFileSync(path.join(root, 'frontend/assets/console-processes.js'), 'utf8'));
  run('bindProcessControls()');
  assert(get('killOpenFin').disabled); assert(get('killMatches').disabled);
  assert.equal(get('killMatchWord').value, 'a180');
  get('adminPc').value = 'testpc'; get('adminPc').dispatchEvent(new w.Event('input'));
  get('killOpenFin').click();
  assert(get('processKillDialog').open);
  assert(get('processKillQuestion').textContent.includes('all processes named openfin.exe on TESTPC, across all sessions'));
  assert.equal(kills.length, 0, 'No remote request before confirmation');
  get('cancelProcessKill').click(); await settle();
  assert.equal(kills.length, 0);
  get('killOpenFin').click(); get('confirmProcessKill').click(); await settle();
  assert.deepEqual(kills[0].payload, {computer: 'TESTPC', value: 'openfin.exe', match: 'exact'});
  assert(get('killOpenFin').disabled && get('killMatches').disabled && get('killBtn').disabled);
  run('quickProcessKill("a180", "contains")'); await settle();
  assert.equal(kills.length, 1, 'Duplicate actions are blocked');
  kills[0].resolve({count: 2, results: [{state: 'terminated'}, {state: 'terminated'}]}); await settle();
  assert(get('quickKillStatus').textContent.includes('TESTPC: 2 terminated'));
  assert(!get('killMatches').disabled);
  get('killMatches').click();
  assert(get('processKillQuestion').textContent.includes('names contain "a180" (case-insensitive)'));
  get('killMatchWord').value = 'b180';
  get('confirmProcessKill').click(); await settle();
  assert.deepEqual(kills[1].payload, {computer: 'TESTPC', value: 'a180', match: 'contains'}, 'Confirmed word is immutable');
  kills[1].resolve({count: 2, results: [{state: 'terminated'}, {state: 'terminated'}, {Process: 'A180.exe', PID: 44, state: 'failed', message: 'Access denied'}]}); await settle();
  assert(get('quickKillStatus').textContent.includes('Access denied'));
  assert.equal(kills.length, 2, 'Partial failures are not retried');
  for (const value of ['', 'a', 'ab', '*', 'a180*', "a180';bad", '.exe', 'a'.repeat(65)]) {
    get('killMatchWord').value = value; get('killMatches').click();
    assert(!get('processKillDialog').open);
  }
  assert.equal(kills.length, 2);
  get('killMatchWord').value = '180'; get('killMatchWord').dispatchEvent(new w.KeyboardEvent('keydown', {key: 'Enter', bubbles: true}));
  assert(get('processKillDialog').open); get('confirmProcessKill').click(); await settle();
  assert.deepEqual(kills[2].payload, {computer: 'TESTPC', value: '180', match: 'contains'});
  kills[2].resolve({count: 0, results: []}); await settle();
  assert(get('quickKillStatus').textContent.includes('no matching process'));
  get('killOpenFin').click(); get('adminPc').value = 'OTHERPC'; get('adminPc').dispatchEvent(new w.Event('input')); await settle();
  assert(!get('processKillDialog').open); assert.equal(kills.length, 3);
  assert(get('quickKillStatus').hidden, 'Changing target clears the previous outcome');
  get('killOpenFin').click(); get('confirmProcessKill').click(); await settle();
  get('adminPc').value = 'NEWPC'; get('adminPc').dispatchEvent(new w.Event('input'));
  kills[3].resolve({count: 1, results: [{state: 'terminated'}]}); await settle();
  assert(get('quickKillStatus').hidden, 'Old target outcome cannot appear on the new target');
  const meta = w.document.createElement('meta'); meta.name = 'atlas-mode'; meta.content = 'viewer'; w.document.head.append(meta);
  run(fs.readFileSync(path.join(root, 'frontend/assets/readonly-console.js'), 'utf8'));
  run('updateProcessActionControls()');
  assert(get('killOpenFin').disabled && get('killMatches').disabled);
  await run('quickProcessKill("openfin.exe")');
  get('killOpenFin').disabled = false; get('killOpenFin').click(); await settle();
  assert.equal(kills.length, 4, 'Read-only mode blocks both direct and delegated actions');
  assert(!get('processKillDialog').open);
  assert.equal(f.errors.length, 0, f.errors.join('\n'));
  w.close(); console.log('PASS: quick kill confirmation, exact/contains payloads, immutable word/target, pending lock, partial/no matches and read-only restrictions.');
})().catch(error => {console.error(error); process.exitCode = 1});
