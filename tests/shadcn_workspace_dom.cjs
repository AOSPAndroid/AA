const assert = require('node:assert/strict');
const fs = require('node:fs');
const { fixture } = require('./ui_fixture.cjs');
(async () => {
  const f = await fixture({ fetch: async () => { throw Error('Workspace launchers must not start a request'); } });
  const { w, run } = f, d = w.document;
  w.ResizeObserver = class { observe() {} unobserve() {} disconnect() {} };
  w.AtlasUI.motion.isReduced = () => true;
  const visited = [];
  d.querySelectorAll('.console-sidebar [data-page]').forEach(button => button.onclick = () => visited.push(button.dataset.page));
  d.querySelector('[data-section="knowledge"]').onclick = event => { event.preventDefault(); visited.push('knowledge'); };
  run(fs.readFileSync('frontend/assets/atlas-interactions.js', 'utf8'));
  await new Promise(resolve => setTimeout(resolve, 80));
  assert.equal(d.querySelectorAll('.workspace-launchers [data-slot="card"]').length, 4);
  d.querySelectorAll('.workspace-launchers [data-slot="button"]').forEach(button => button.click());
  assert.deepEqual(visited, ['active-directory', 'admin', 'packages', 'knowledge']);
  assert.equal(d.querySelectorAll('.workspace-launchers [role="heading"]').length, 4);
  const mode = d.createElement('meta'); mode.name = 'atlas-mode'; mode.content = 'viewer'; d.head.append(mode);
  run(fs.readFileSync('frontend/assets/readonly-console.js', 'utf8'));
  assert(w.AtlasReadOnly, 'Read-only policy is loaded');
  w.AtlasReadOnly.enforce();
  assert.equal(d.querySelectorAll('.workspace-launchers [data-tool]').length, 0, 'Navigation must not masquerade as a remote tool');
  assert.equal(d.querySelectorAll('.workspace-launchers button:disabled').length, 0);
  visited.length = 0;
  d.querySelectorAll('.workspace-launchers [data-slot="button"]').forEach(button => button.click());
  assert.deepEqual(visited, ['active-directory', 'admin', 'packages', 'knowledge']);
  assert.deepEqual(f.errors, []);
  w.dispatchEvent(new w.Event('pagehide'));
  w.close();
  console.log('PASS: shadcn cards retain accessible headings and existing navigation; no remote actions');
})().catch(error => { console.error(error); process.exitCode = 1; });
