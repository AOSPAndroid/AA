"""Generate dark-mode counterparts for hard-coded light colours in Atlas stylesheets.

Older stylesheets set fixed light backgrounds (#fff, #fff3da, #edf6fa...) and dark text that the
theme tokens never reach, so parts of the console stayed light in dark mode. This reads every
first-party stylesheet the pages load and writes, between markers in design-system.css, one
html[data-theme="dark"] rule per such selector, mapping each colour by hue onto the dark tokens:
neutral -> surface, yellow -> warning, green -> success, red -> danger, blue -> selected.
The block sits at the end of design-system.css with no added specificity, so it replaces each light
original and nothing else; hand-tuned html[data-theme="dark"] rules keep priority.

Run after changing colours in a stylesheet:  python tools/build_dark_overrides.py
"""
import colorsys
import re
from pathlib import Path

import tinycss2
from tinycss2.color3 import parse_color

ROOT = Path(__file__).resolve().parents[1]
SOURCES = ['frontend/assets/ui-tokens.css', 'frontend/assets/readonly-console.css', 'frontend/assets/atlas-theme.css',
           'frontend/assets/machine-health.css', 'frontend/assets/atlas-shell.css', 'frontend/assets/catalogue.css',
           'frontend/assets/console-psexec.css', 'frontend/assets/knowledge-base.css', 'atlas/style.css',
           'atlas/operations.css', 'atlas/official.css', 'frontend/assets/design-system.css']
TARGET = ROOT / 'frontend/assets/design-system.css'
START, END = '/* dark-auto:start (generated by tools/build_dark_overrides.py; do not edit) */', '/* dark-auto:end */'
# Map labels and drawings keep their own colours; the floor plan is inverted as a whole.
SKIP = re.compile(r'data-theme|map-name|room-label|amenity-tag|plan-canvas|map-labels|drawio|mermaid|xterm|::selection|print-only|:root')
DARK = {'neutral': (22, 27, 34), 'neutral-subtle': (28, 35, 44)}


def luminance(rgba):
    r, g, b = rgba[:3]
    return 0.2126 * r + 0.7152 * g + 0.0722 * b


def family(rgba):
    h, l, s = colorsys.rgb_to_hls(*rgba[:3])
    if s < 0.18 or l > 0.97:
        return 'neutral'
    h *= 360
    if h < 18 or h >= 330:
        return 'red'
    if h < 65:
        return 'yellow'
    if h < 170:
        return 'green'
    if h < 255:
        return 'blue'
    return 'purple'


def dark_background(rgba):
    kind = family(rgba)
    if kind == 'neutral':
        token = 'var(--atlas-surface)' if luminance(rgba) > 0.955 else 'var(--atlas-surface-subtle)'
        if rgba[3] < 1:
            r, g, b = DARK['neutral']
            return f'rgb({r} {g} {b} / {rgba[3]:.2f})'
        return token
    return {'red': 'var(--atlas-danger-bg)', 'yellow': 'var(--atlas-warning-bg)', 'green': 'var(--atlas-success-bg)',
            'blue': 'var(--atlas-selected)', 'purple': 'var(--atlas-indigo-bg, #1d1f45)'}[kind]


def dark_text(rgba):
    return {'neutral': 'var(--atlas-text)', 'red': 'var(--atlas-danger-text)', 'yellow': 'var(--atlas-warning)',
            'green': 'var(--atlas-success)', 'blue': 'var(--atlas-focus)', 'purple': 'var(--atlas-indigo, #a5b4fc)'}[family(rgba)]


def colours(tokens):
    for token in tokens:
        if token.type in ('hash', 'function', 'ident'):
            colour = parse_color(token)
            if colour is not None and not isinstance(colour, str):
                yield tuple(colour)
        if token.type == 'function' and token.lower_name in ('linear-gradient', 'radial-gradient'):
            yield from colours(token.arguments)


def light(rgba, limit):
    return rgba[3] > 0.45 and luminance(rgba) > limit


def convert(declarations):
    """Dark declarations for one rule, or []."""
    out, background_changed, background_declared = [], False, False
    for d in declarations:
        if d.type != 'declaration':
            continue
        name, found = d.lower_name, list(colours(d.value))
        bang = ' !important' if d.important else ''
        if name in ('background', 'background-color'):
            background_declared = True
            if any(t.type == 'url' or (t.type == 'function' and t.lower_name == 'url') for t in d.value):
                continue
            lights = [c for c in found if light(c, 0.8 if family(c) == 'neutral' else 0.74)]
            if lights and len(lights) == len(found):
                out.append(f'background:{dark_background(lights[0])}{bang}' if name == 'background' else f'background-color:{dark_background(lights[0])}{bang}')
                background_changed = True
        elif name in ('border', 'border-color', 'border-top', 'border-right', 'border-bottom', 'border-left',
                      'border-top-color', 'border-right-color', 'border-bottom-color', 'border-left-color', 'outline-color'):
            if found and all(light(c, 0.7) for c in found):
                prop = name if name.endswith('color') else (name + '-color' if name != 'border' else 'border-color')
                out.append(f'{prop}:var(--atlas-line){bang}')
    for d in declarations:
        if d.type == 'declaration' and d.lower_name == 'color' and (background_changed or not background_declared):
            found = list(colours(d.value))
            if found:
                c = found[0]
                limit = 0.45 if family(c) == 'neutral' else 0.55
                if c[3] > 0.45 and luminance(c) < limit:
                    out.append(f'color:{dark_text(c)}{" !important" if d.important else ""}')
    return out


def prefix(selector):
    # :where() adds no specificity: a dark rule replaces its light original (it comes later, at the
    # same strength) but never outranks other rules, such as accent buttons or hand-tuned dark rules.
    selector = selector.strip()
    if selector.startswith('html'):
        return 'html:where([data-theme="dark"])' + selector[4:]
    return ':where(html[data-theme="dark"]) ' + selector


def rules(nodes, media=None):
    for node in nodes:
        if node.type == 'at-rule' and node.lower_at_keyword in ('media', 'supports', 'layer') and node.content:
            condition = tinycss2.serialize(node.prelude).strip()
            if node.lower_at_keyword == 'media' and 'print' in condition:
                continue
            inner = tinycss2.parse_rule_list(node.content, skip_comments=True, skip_whitespace=True)
            yield from rules(inner, (media or []) + [f'@{node.lower_at_keyword} {condition}'])
        elif node.type == 'qualified-rule':
            selectors = [s for s in split_selectors(tinycss2.serialize(node.prelude)) if s and not SKIP.search(s)]
            if not selectors:
                continue
            body = convert(tinycss2.parse_declaration_list(node.content, skip_comments=True, skip_whitespace=True))
            if body:
                yield media, ','.join(prefix(s) for s in selectors), ';'.join(body)


def split_selectors(text):
    parts, depth, current = [], 0, ''
    for ch in text:
        depth += ch in '([' ; depth -= ch in ')]'
        if ch == ',' and depth == 0:
            parts.append(current.strip()); current = ''
        else:
            current += ch
    return parts + [current.strip()]


def main(check=False):
    original = target = TARGET.read_text(encoding='utf-8')
    if START in target:
        before, rest = target.split(START, 1)
        target = before.rstrip('\n') + '\n' + rest.split(END, 1)[1].lstrip('\n')
    lines, seen = [], set()
    for source in SOURCES:
        text = (ROOT / source).read_text(encoding='utf-8')
        if source.endswith('design-system.css'):
            text = text.split(START)[0] + (text.split(END, 1)[1] if END in text else '')
        for media, selector, body in rules(tinycss2.parse_stylesheet(text, skip_comments=True, skip_whitespace=True)):
            rule = f'{selector}{{{body}}}'
            for condition in reversed(media or []):
                rule = f'{condition}{{{rule}}}'
            if rule not in seen:
                seen.add(rule); lines.append(rule)
    block = '\n'.join([START, *lines, END])
    result = target.rstrip('\n') + '\n' + block + '\n'
    if check:
        return result == original
    TARGET.write_text(result, encoding='utf-8')
    print(f'{len(lines)} dark rules written to {TARGET.relative_to(ROOT)}')


if __name__ == '__main__':
    import sys
    if '--check' in sys.argv:
        sys.exit(0 if main(check=True) else 'Dark rules are out of date: run python tools/build_dark_overrides.py')
    main()
